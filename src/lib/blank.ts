/* NOTE 기본 이미지의 오로라 띠 위치를 글마다 조금씩 어긋나게 한다 [기본 이미지]
 * - 한 화면에 기본 이미지가 여러 개 나오면 똑같은 판이 찍어낸 듯 반복된다
 * - 슬러그에서 뽑으므로 글마다 늘 같은 자리다. 새로고침해도 흔들리지 않는다
 */
export function blankLight(slug: string): string {
  let h = 0;
  for (let i = 0; i < slug.length; i += 1) h = (h * 31 + slug.charCodeAt(i)) % 997;
  // 띠 세 줄기를 각각 다른 폭으로 민다. 범위를 좁게 둬 구도가 무너지지 않게 한다
  return `--au-1:${14 + (h % 22)}%;--au-2:${50 + ((h >> 2) % 18)}%;--au-3:${78 + ((h >> 4) % 16)}%`;
}
